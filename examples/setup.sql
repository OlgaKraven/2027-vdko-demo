-- Выполнить в psql от администратора на чистом учебном экземпляре.
CREATE DATABASE :"dbname";
\connect :dbname

BEGIN;
CREATE ROLE client01 LOGIN;
CREATE ROLE client02 LOGIN;
CREATE ROLE client03 LOGIN;
CREATE ROLE client04 LOGIN;
CREATE ROLE client05 LOGIN;
REVOKE CONNECT ON DATABASE :"dbname" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"dbname" TO client01, client02, client03, client04, client05;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO client01, client02, client03, client04, client05;

CREATE TABLE public.clients (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    email varchar(254) NOT NULL,
    reg_date date NOT NULL
);
INSERT INTO public.clients (name, email, reg_date) VALUES
    ('Учебный клиент А', 'a@example.test', DATE '2027-01-10'),
    ('Учебный клиент Б', 'b@example.test', DATE '2027-01-11');

GRANT SELECT, INSERT ON public.clients TO client01, client02;
GRANT SELECT ON public.clients TO client03;
GRANT SELECT, UPDATE ON public.clients TO client04;
GRANT SELECT, DELETE ON public.clients TO client05;
COMMIT;

