CREATE ROLE client05 LOGIN;
REVOKE CONNECT ON DATABASE :"dbname" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"dbname" TO client01, client02, client03, client04, client05;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO client01, client02, client03, client04, client05;

