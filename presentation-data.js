function databaseSlides(route) {
  const steps = (route.steps ?? COURSE.tasks.find(task => task.id === 'M2').steps).slice(0, 3);
  const screensShown = new Set();
  const demonstration = steps.flatMap(({example}) => example.points.flatMap(point => {
    const items = point.actions ?? [];
    const result = point.result;
    const screenshots = [...(point.screenshots ?? []), ...(result?.screenshots ?? [])].flatMap(key => {
      const screenshot = DATABASE_SCREENSHOTS[key];
      if (screensShown.has(key) || !screenshotMatchesRoute(screenshot,route.id)) return [];
      screensShown.add(key);
      return [screenshot];
    });
    const resultTable = result?.table ?? point.table;
    const verification = result?.text ?? example.result;
    const code = point.code?.split('\n').length <= 8 ? point.code : undefined;
    const notes = [[example.input, verification].join(' '), point.code].filter(Boolean).join('\n\n');
    return [
      {title: point.title, items, text: point.text, notes},
      ...(resultTable || code || result?.output || result?.text ? [{
        title: point.title + ' · проверка',
        table: resultTable ? [resultTable.columns, ...resultTable.rows] : undefined,
        text: !resultTable && !result?.output ? result?.text : undefined,
        code: result?.output ?? (resultTable ? undefined : code),
        notes: verification + (code ? '\n\n' + code : '')
      }] : []),
      ...screenshots.map(screenshot => ({
        title: screenshot.title,
        type: 'screenshot',
        screenshot,
        notes: [screenshot.hint, verification].join(' ')
      }))
    ];
  }));
  return [
    {
      title: route.title,
      items: ['Создаём corpdata_07, таблицу clients и пять пользователей.',
        'Из отдельного подключения выполняем разрешённую операцию и фиксируем результат.',
        'Выгружаем структуру и две исходные строки в clients.sql.'],
      notes: 'Откройте чистый учебный экземпляр для выбранного маршрута. Проверьте адрес и порт до показа. В примере используем номер места 07.'
    },
    ...demonstration,
    {
      type: 'question',
      title: 'Чтение разрешено, обновление отклонено',
      text: 'Под client03 запрос SELECT вернул две строки, а сервер отклонил UPDATE. Что записать в отчёт?',
      answer: 'Зафиксируйте имя пользователя, имя базы, две строки из SELECT и сообщение об отказе на UPDATE. Матрица прав для client03 подтверждена.',
      notes: 'Попросите найти в выводе имя роли и базы. Обсудите, почему проверка под администратором не подтверждает права client03.'
    },
    ...windowsSlides
  ];
}

